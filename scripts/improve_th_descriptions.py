def improve_description(text: str, exhibit_name: str) -> str:
    """
    改进展品描述
    """
    import re

    original = text.strip()

    # 尝试匹配改进规则
    for pattern, replacement in IMPROVEMENT_RULES['patterns']:
        match = re.match(pattern, original)
        if match:
            try:
                improved = replacement
                # 如果有捕获组，替换
                if match.groups():
                    improved = match.expand(replacement)
                return improved
            except Exception as e:
                print(f"[WARNING] Pattern match failed: {e}")
                continue

    # 如果没有匹配到规则，检查是否需要改进
    if len(original) < 30:
        # 太短了，需要补充
        return f"{original}这件作品通过独特的艺术表现形式，展现了深厚的文化底蕴和艺术家的创作理念，为观众提供了丰富的视觉体验和审美享受。"

    return original


def process_th_file():
    """处理 TH.xlsx 文件"""
    input_file = 'skills/topology/assets/TH.xlsx'

    print(f"[INFO] Reading: {input_file}")

    wb = openpyxl.load_workbook(input_file)
    sheet = wb.active

    print(f"[INFO] Total rows: {sheet.max_row}")

    # 创建新工作簿
    new_wb = openpyxl.Workbook()
    new_sheet = new_wb.active

    # 复制表头
    for cell in sheet[1]:
        new_cell = new_sheet.cell(row=1, column=cell.column, value=cell.value)

    improved_count = 0
    skipped_count = 0

    # 处理每一行
    for row_idx in range(2, sheet.max_row + 1):
        # 复制所有列
        for col_idx in range(1, sheet.max_column + 1):
            cell = sheet.cell(row=row_idx, column=col_idx)
            new_cell = new_sheet.cell(row=row_idx, column=col_idx, value=cell.value)

            if col_idx == 4 and cell.value:  # Visual_Features 列
                original = str(cell.value).strip()
                exhibit_name = str(sheet.cell(row=row_idx, column=2).value)  # Name列

                improved = improve_description(original, exhibit_name)

                if improved != original:
                    improved_count += 1
                    new_cell.value = improved

                    if improved_count <= 10:  # 只显示前10个
                        print(f"\n[IMPROVED] Row {row_idx}: {exhibit_name}")
                        print(f"  Before: {original[:80]}...")
                        print(f"  After:  {improved[:80]}...")
                else:
                    skipped_count += 1

    # 备份原文件
    backup_file = input_file.replace('.xlsx', '_before_improvement.xlsx')
    shutil.copy(input_file, backup_file)
    print(f"\n[INFO] Backed up to: {backup_file}")

    # 保存新文件
    new_wb.save(input_file)

    print(f"\n" + "="*80)
    print(f"[SUCCESS] Done!")
    print(f"[INFO] Improved: {improved_count}")
    print(f"[INFO] Skipped: {skipped_count}")
    print(f"[INFO] File updated: {input_file}")


if __name__ == '__main__':
    process_th_file()
